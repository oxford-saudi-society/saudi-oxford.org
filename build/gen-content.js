'use strict';
/* Writes netlify/lib/content.generated.mjs: the published programme (events, venues, labels, settings)
   as an ES module, so the Functions bundle carries the same content the static pages were built from. */
const fs = require('fs');
const path = require('path');
const EV = require('./events');
const ROOT = path.join(__dirname, '..');
const readJson = (p) => JSON.parse(fs.readFileSync(p, 'utf8'));
function generate() {
  const events = EV.loadEvents().map((e) => Object.assign({}, e, { start: e.start.toISOString(), end: e.end.toISOString() }));
  const venues = readJson(path.join(ROOT, 'src/content/venues.json'));
  const labels = readJson(path.join(ROOT, 'src/content/event-labels.json'));
  const s = readJson(path.join(ROOT, 'src/content/settings.json'));
  const settings = { siteName: s.siteName, domain: s.domain, email: s.email, membershipEmail: s.membershipEmail || s.email, treasurerEmail: s.treasurerEmail || s.email, committeeNotifyEmail: s.committeeNotifyEmail || s.membershipEmail || s.email, adminEmails: s.adminEmails || [], fees: s.fees || {}, payLinks: s.payLinks || {}, bank: s.bank || {}, privacyVersion: (s.privacy && s.privacy.version) || '2026-11' };
  const out = `// GENERATED by build/gen-content.js — do not edit. Source: src/content/**\nexport const GENERATED_AT = ${JSON.stringify(new Date().toISOString())};\nexport const EVENTS = ${JSON.stringify(events)};\nexport const VENUES = ${JSON.stringify(venues)};\nexport const LABELS = ${JSON.stringify(labels)};\nexport const SETTINGS = ${JSON.stringify(settings)};\n`;
  const dest = path.join(ROOT, 'netlify/lib/content.generated.mjs');
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  const prev = fs.existsSync(dest) ? fs.readFileSync(dest, 'utf8').replace(/GENERATED_AT = "[^"]+"/, '') : '';
  if (prev !== out.replace(/GENERATED_AT = "[^"]+"/, '')) fs.writeFileSync(dest, out);
  return events.length;
}
module.exports = { generate };
if (require.main === module) console.log('content module:', generate(), 'events');
